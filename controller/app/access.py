"""Access (SPEC §18.2): protect path prefixes of a site with an e-mailed one-time code and/or an IP
allow list. Section `access`, plan feature `access`.

access_secret
-------------
32 random bytes per site, generated by the controller (when the section is first saved enabled, or
by ``POST /api/v1/sites/{d}/access/rotate``), stored encrypted in ``sites.integration_secrets``
(site_secrets key ``access``) and sent to the edges in the site config as **64 lowercase hex
characters** (``sites[].access.secret``). Every HMAC below is keyed with the **32 raw bytes**
(hex-decoded), never with the hex text. Rotating it invalidates every session cookie and code.

One-time code (``otp_code``; the edge recomputes it locally on verify)::

    window = floor(unix_seconds / 300)
    msg    = UTF-8 bytes of  "otp|" + app_id + "|" + lower(email) + "|" + decimal(window)
    d      = HMAC-SHA256(key = bytes.fromhex(access_secret), msg)            # 32 bytes
    off    = d[31] & 0x0f
    bin    = ((d[off] & 0x7f) << 24) | (d[off+1] << 16) | (d[off+2] << 8) | d[off+3]
    code   = decimal(bin mod 1_000_000), left-padded with "0" to 6 digits

(RFC 4226 dynamic truncation over HMAC-SHA256.) `lower` is ASCII lower-casing of the trimmed
address (only ASCII addresses are accepted). The verifier accepts the current and the previous
window. Test vectors: tests/test_wave10_access.py::VECTORS.

Usage (per host-hour item): ``access: {ok, fail, otp}`` (deltas, summed) and ``access_events:
[{t, app, email_hash, ok}]`` (≤50 per item; the controller keeps the newest 200 per site-hour and
``GET .../access/log`` returns the newest 200). ``email_hash`` is chosen by the edge (8..64 lowercase
hex; recommended: first 16 hex of HMAC-SHA256(raw access_secret, "email|" + lower(email))).
"""

